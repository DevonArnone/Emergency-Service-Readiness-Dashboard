    CONSTRAINT UNIT_ASSIGNMENTS_PK PRIMARY KEY (ORGANIZATION_ID, ASSIGNMENT_ID)
);

CREATE TABLE IF NOT EXISTS ANALYTICS.UNIT_READINESS_HOURLY (
    ORGANIZATION_ID VARCHAR(64) NOT NULL,
    HOUR_START TIMESTAMP_TZ NOT NULL,
    UNIT_ID VARCHAR(64) NOT NULL,
    STATION_ID VARCHAR(64),
    UNIT_TYPE VARCHAR(50),
    MINIMUM_STAFF NUMBER(9, 0),
    STAFF_PRESENT NUMBER(9, 0),
    READINESS_SCORE NUMBER(5, 2),
    UNDERSTAFFED_FLAG BOOLEAN,
    MISSING_CERTIFICATIONS ARRAY,
    SOURCE_EVENT_ID VARCHAR(128) NOT NULL,
    UPDATED_AT TIMESTAMP_TZ NOT NULL DEFAULT CURRENT_TIMESTAMP(),
    CONSTRAINT UNIT_READINESS_HOURLY_PK PRIMARY KEY (ORGANIZATION_ID, HOUR_START, UNIT_ID)
)
CLUSTER BY (ORGANIZATION_ID, TO_DATE(HOUR_START));

CREATE TABLE IF NOT EXISTS ANALYTICS.INCIDENT_ACTIVITY_HOURLY (
    ORGANIZATION_ID VARCHAR(64) NOT NULL,
    HOUR_START TIMESTAMP_TZ NOT NULL,
    PRIORITY VARCHAR(20) NOT NULL,
    EVENTS NUMBER(38, 0) NOT NULL,
    DISTINCT_INCIDENTS NUMBER(38, 0) NOT NULL,
    FIRST_EVENT_AT TIMESTAMP_TZ,
    LAST_EVENT_AT TIMESTAMP_TZ,
    UPDATED_AT TIMESTAMP_TZ NOT NULL DEFAULT CURRENT_TIMESTAMP(),
    CONSTRAINT INCIDENT_ACTIVITY_HOURLY_PK PRIMARY KEY (ORGANIZATION_ID, HOUR_START, PRIORITY)
)
CLUSTER BY (ORGANIZATION_ID, TO_DATE(HOUR_START));

