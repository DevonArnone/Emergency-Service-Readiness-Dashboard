-- Tenant-scoped warehouse objects. PostgreSQL remains the source of truth.

USE ROLE AEGIS_PLATFORM_ADMIN;
USE WAREHOUSE AEGIS_INGEST;
USE DATABASE AEGIS_ANALYTICS;

CREATE TABLE IF NOT EXISTS SECURITY.ROLE_ORGANIZATION_ACCESS (
    ROLE_NAME VARCHAR(255) NOT NULL,
    ORGANIZATION_ID VARCHAR(64) NOT NULL,
    GRANTED_AT TIMESTAMP_TZ NOT NULL DEFAULT CURRENT_TIMESTAMP(),
    GRANTED_BY VARCHAR(255) NOT NULL DEFAULT CURRENT_USER(),
    CONSTRAINT ROLE_ORGANIZATION_ACCESS_PK PRIMARY KEY (ROLE_NAME, ORGANIZATION_ID)
)
COMMENT = 'Explicit reader-role to tenant mapping used by the row access policy';

CREATE OR ALTER ROW ACCESS POLICY SECURITY.TENANT_ACCESS_POLICY
AS (ROW_ORGANIZATION_ID VARCHAR) RETURNS BOOLEAN ->
    CURRENT_ROLE() IN ('ACCOUNTADMIN', 'AEGIS_PLATFORM_ADMIN', 'AEGIS_LOADER', 'AEGIS_TRANSFORMER')
    OR EXISTS (
        SELECT 1
        FROM SECURITY.ROLE_ORGANIZATION_ACCESS ACCESS_MAP
        WHERE ACCESS_MAP.ROLE_NAME = CURRENT_ROLE()
          AND ACCESS_MAP.ORGANIZATION_ID = ROW_ORGANIZATION_ID
    );

CREATE TABLE IF NOT EXISTS RAW.OPERATIONAL_EVENTS (
    ORGANIZATION_ID VARCHAR(64) NOT NULL,
    EVENT_ID VARCHAR(128) NOT NULL,
    EVENT_TYPE VARCHAR(160) NOT NULL,
    PRIORITY VARCHAR(20) NOT NULL,
    TOPIC_CLASS VARCHAR(20) NOT NULL,
    SOURCE VARCHAR(120) NOT NULL,
    SCHEMA_VERSION NUMBER(9, 0) NOT NULL,
    AGGREGATE_TYPE VARCHAR(80) NOT NULL,
    AGGREGATE_ID VARCHAR(128) NOT NULL,
    OCCURRED_AT TIMESTAMP_TZ NOT NULL,
    PAYLOAD VARIANT NOT NULL,
    KAFKA_TOPIC VARCHAR(255),
    KAFKA_PARTITION NUMBER(9, 0),
    KAFKA_OFFSET NUMBER(38, 0),
    INGESTED_AT TIMESTAMP_TZ NOT NULL DEFAULT CURRENT_TIMESTAMP(),
    CONSTRAINT OPERATIONAL_EVENTS_PK PRIMARY KEY (ORGANIZATION_ID, EVENT_ID)
)
CLUSTER BY (ORGANIZATION_ID, TO_DATE(OCCURRED_AT), EVENT_TYPE)
COMMENT = 'Versioned, tenant-scoped events normalized from Kafka';

CREATE TABLE IF NOT EXISTS RAW.STATIONS (
    ORGANIZATION_ID VARCHAR(64) NOT NULL,
    STATION_ID VARCHAR(64) NOT NULL,
    STATION_NUMBER VARCHAR(20),
    NAME VARCHAR(180) NOT NULL,
    BATTALION_ID VARCHAR(64),
    ADDRESS VARCHAR(240),
    LATITUDE FLOAT,
    LONGITUDE FLOAT,
    UPDATED_AT TIMESTAMP_TZ NOT NULL DEFAULT CURRENT_TIMESTAMP(),
    CONSTRAINT STATIONS_PK PRIMARY KEY (ORGANIZATION_ID, STATION_ID)
);

CREATE TABLE IF NOT EXISTS RAW.UNITS (
    ORGANIZATION_ID VARCHAR(64) NOT NULL,
    UNIT_ID VARCHAR(64) NOT NULL,
    STATION_ID VARCHAR(64),
    CALL_SIGN VARCHAR(80) NOT NULL,
    UNIT_TYPE VARCHAR(50) NOT NULL,
    MINIMUM_STAFF NUMBER(9, 0) NOT NULL,
    REQUIRED_CERTIFICATIONS ARRAY NOT NULL,
    OPERATIONAL_STATUS VARCHAR(40) NOT NULL DEFAULT 'AVAILABLE',
    UPDATED_AT TIMESTAMP_TZ NOT NULL DEFAULT CURRENT_TIMESTAMP(),
    CONSTRAINT UNITS_PK PRIMARY KEY (ORGANIZATION_ID, UNIT_ID)
);

CREATE TABLE IF NOT EXISTS RAW.PERSONNEL (
    ORGANIZATION_ID VARCHAR(64) NOT NULL,
    PERSONNEL_ID VARCHAR(64) NOT NULL,
